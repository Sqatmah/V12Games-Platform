// ═══ نظام الترجمة ═══

function getLang() {
  return localStorage.getItem('v12_lang') || 'ar';
}

function setLang(lang) {
  localStorage.setItem('v12_lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  translatePage(lang);
  updateLangBtn(lang);
}

function t(key) {
  const lang = getLang();
  return translations[lang][key] || translations['ar'][key] || key;
}

function translatePage(lang) {
  // ترجم كل العناصر اللي عندها data-t
  document.querySelectorAll('[data-t]').forEach(el => {
    const key = el.getAttribute('data-t');
    const tr = translations[lang][key];
    if (tr) el.textContent = tr;
  });

  // ترجم placeholder
  document.querySelectorAll('[data-t-placeholder]').forEach(el => {
    const key = el.getAttribute('data-t-placeholder');
    const tr = translations[lang][key];
    if (tr) el.placeholder = tr;
  });

  // اتجاه الصفحة
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;
}

function updateLangBtn(lang) {
  const btn = document.getElementById('lang-toggle-btn');
  if (!btn) return;
  if (lang === 'ar') {
    btn.innerHTML = '<span class="text-base">🇺🇸</span><span>EN</span>';
    btn.setAttribute('onclick', "setLang('en')");
  } else {
    btn.innerHTML = '<span class="text-base">🇸🇦</span><span>AR</span>';
    btn.setAttribute('onclick', "setLang('ar')");
  }
}

// تشغيل عند تحميل الصفحة
document.addEventListener('DOMContentLoaded', function() {
  const lang = getLang();
  setLang(lang);
});